import {DataLoader, Tab, Tabs} from 'argo-ui';
import * as React from 'react';
import {Context} from '../../../shared/context';
import * as models from '../../../shared/models';
import {services} from '../../../shared/services';
import {ApplicationNodeInfo} from '../application-node-info/application-node-info';
import {ApplicationResourceEvents} from '../application-resource-events/application-resource-events';
import {ResourceIcon} from '../resource-icon';
import {ResourceLabel} from '../resource-label';
import type {ResourceTreeNode} from '../application-resource-tree/application-resource-tree';
import {ComparisonStatusIcon, getAppUrl, HealthStatusIcon, nodeKey} from '../utils';
import './resource-details.scss';

interface AppSetGeneratedAppDetailsProps {
    node: models.ResourceNode;
}

// Shows the details of a child Application generated by an ApplicationSet, when the
// Application node is selected in the ApplicationSet resource tree or list. Mirrors the
// app-of-apps resource view: the full live Application manifest (including status) is shown
// inline in the sliding panel instead of navigating away from the ApplicationSet. The
// DETAILS button still offers a way to open the Application's own page.
export const AppSetGeneratedAppDetails = (props: AppSetGeneratedAppDetailsProps) => {
    const {node} = props;
    const appContext = React.useContext(Context);
    const tab = new URLSearchParams(appContext.history.location.search).get('tab');

    return (
        <div style={{width: '100%', height: '100%'}}>
            {/* Include the node's resourceVersion so the manifest refreshes when the watch stream reports a change
                to the selected Application (same signal ResourceDetails relies on). */}
            <DataLoader
                input={`${nodeKey(node)}/${node.resourceVersion}`}
                load={async () => (await services.applications.get(node.name, node.namespace, 'application')) as models.Application}>
                {app => {
                    const tabs: Tab[] = [
                        {
                            title: 'SUMMARY',
                            icon: 'fa fa-file-alt',
                            key: 'summary',
                            content: (
                                <ApplicationNodeInfo
                                    application={app}
                                    live={app as unknown as models.State}
                                    controlled={null}
                                    node={node}
                                    links={null}
                                    showApplicationReference={true}
                                />
                            )
                        },
                        {
                            title: 'EVENTS',
                            key: 'events',
                            content: (
                                <div className='application-resource-events'>
                                    <ApplicationResourceEvents applicationName={app.metadata.name} applicationNamespace={app.metadata.namespace} />
                                </div>
                            )
                        }
                    ];

                    return (
                        <React.Fragment>
                            <div className='resource-details__header'>
                                <div style={{display: 'flex', flexDirection: 'column', marginRight: '15px', alignItems: 'center', fontSize: '12px'}}>
                                    <ResourceIcon group={node.group} kind={node.kind} />
                                    {ResourceLabel({kind: node.kind})}
                                </div>
                                <div className='resource-details__header-name'>
                                    <h1 className='resource-details__header-title'>{node.name}</h1>
                                    <span className='resource-details__header-status'>
                                        {(node as ResourceTreeNode).status && (
                                            <span style={{marginRight: '5px'}}>
                                                <ComparisonStatusIcon status={(node as ResourceTreeNode).status} resource={node as ResourceTreeNode} />
                                            </span>
                                        )}
                                        {app.status?.health && <HealthStatusIcon state={app.status.health} />}
                                    </span>
                                </div>
                                <div className='resource-details__header-actions'>
                                    <button onClick={() => appContext.navigation.goto(`/${getAppUrl(app)}`)} className='argo-button argo-button--base'>
                                        <i className='fa fa-fw fa-info-circle' /> <span className='show-for-large'>DETAILS</span>
                                    </button>
                                </div>
                            </div>
                            <Tabs
                                navTransparent={true}
                                tabs={tabs}
                                selectedTabKey={tab}
                                onTabSelected={selected => appContext.navigation.goto('.', {tab: selected}, {replace: true})}
                            />
                        </React.Fragment>
                    );
                }}
            </DataLoader>
        </div>
    );
};
