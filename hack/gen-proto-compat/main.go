// gen-proto-compat generates a <pkg>/proto_reflect_compat.go file that makes
// gogo-generated message types satisfy the google.golang.org/protobuf
// proto.Message interface.
//
// grpc-gateway v2 generated code and google.golang.org/grpc's default codec
// require messages to implement ProtoReflect() protoreflect.Message. The
// gogo-generated types cannot implement it directly, so for each message type
// this generator emits a method-less defined type (shim) sharing the same
// memory layout, and implements ProtoReflect by wrapping the shim with
// protoadapt.MessageV2Of. Because the shim exposes the gogo-generated
// Descriptor() method, protoimpl reconstructs the real message descriptor from
// the serialized FileDescriptorProto (the same mechanism used for legacy
// golang/protobuf v1 messages), and delegates wire marshaling to the
// gogo-generated XXX_Marshal/XXX_Unmarshal/XXX_Size methods. Wire bytes stay
// identical to the gogo encoding.
//
// Usage: go run ./hack/gen-proto-compat <pb.go file>...
//
// The output file is written next to the first input file.
package main

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	if len(os.Args) < 2 {
		fmt.Fprintln(os.Stderr, "usage: gen-proto-compat <pb.go file>...")
		os.Exit(1)
	}

	pkgName := ""
	types := map[string]bool{}
	for _, file := range os.Args[1:] {
		fset := token.NewFileSet()
		f, err := parser.ParseFile(fset, file, nil, 0)
		if err != nil {
			fmt.Fprintf(os.Stderr, "parse %s: %v\n", file, err)
			os.Exit(1)
		}
		if pkgName == "" {
			pkgName = f.Name.Name
		} else if pkgName != f.Name.Name {
			fmt.Fprintf(os.Stderr, "package mismatch: %s vs %s\n", pkgName, f.Name.Name)
			os.Exit(1)
		}
		for _, decl := range f.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if !ok || fn.Name.Name != "XXX_Marshal" || fn.Recv == nil || len(fn.Recv.List) != 1 {
				continue
			}
			star, ok := fn.Recv.List[0].Type.(*ast.StarExpr)
			if !ok {
				continue
			}
			ident, ok := star.X.(*ast.Ident)
			if !ok {
				continue
			}
			types[ident.Name] = true
		}
	}

	names := make([]string, 0, len(types))
	for name := range types {
		names = append(names, name)
	}
	sort.Strings(names)
	if len(names) == 0 {
		fmt.Fprintln(os.Stderr, "no gogo message types (XXX_Marshal receivers) found")
		os.Exit(1)
	}

	var b strings.Builder
	b.WriteString("// Code generated by hack/gen-proto-compat. DO NOT EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// This file makes the gogo-generated message types in this package satisfy\n")
	b.WriteString("// the google.golang.org/protobuf proto.Message interface, which is required\n")
	b.WriteString("// by grpc-gateway v2 generated code and by google.golang.org/grpc's default\n")
	b.WriteString("// codec when these types appear as (or inside) gRPC request/response\n")
	b.WriteString("// messages. ProtoReflect returns a functional reflective view backed by\n")
	b.WriteString("// protoadapt legacy wrapping: the real message descriptor is reconstructed\n")
	b.WriteString("// from the gogo-generated serialized FileDescriptorProto (via the shim's\n")
	b.WriteString("// Descriptor method) and wire marshaling is delegated to the gogo-generated\n")
	b.WriteString("// XXX_Marshal/XXX_Unmarshal/XXX_Size methods, keeping wire bytes identical\n")
	b.WriteString("// to the gogo encoding.\n")
	fmt.Fprintf(&b, "\npackage %s\n\n", pkgName)
	b.WriteString("import (\n")
	b.WriteString("\t\"google.golang.org/protobuf/protoadapt\"\n")
	b.WriteString("\t\"google.golang.org/protobuf/reflect/protoreflect\"\n")
	b.WriteString("\t\"google.golang.org/protobuf/runtime/protoiface\"\n")
	b.WriteString(")\n")
	b.WriteString(`
// legacyMessageShim is implemented by the per-type shims below, delegating to
// the gogo-generated marshalers.
type legacyMessageShim interface {
	protoadapt.MessageV1
	Marshal() ([]byte, error)
	Unmarshal([]byte) error
	Size() int
}

// protoMessageView wraps the protoimpl reflective view of a shim. It overrides
// ProtoMethods so that all wire operations (top-level and nested inside
// protoc-gen-go generated messages) go through the gogo-generated
// Marshal/Unmarshal/Size methods, keeping wire bytes identical to the gogo
// encoding. It also hides the wrapped view's ProtoMessageInfo method, which
// forces google.golang.org/protobuf field coders onto their generic path:
// protoimpl's struct-tag-driven fast path cannot handle gogo value-typed
// (nullable=false) message fields.
type protoMessageView struct {
	protoreflect.Message
	shim legacyMessageShim
}

func (v protoMessageView) ProtoMethods() *protoiface.Methods { return &legacyShimMethods }

var legacyShimMethods = protoiface.Methods{
	Flags: protoiface.SupportMarshalDeterministic,
	// CheckInitialized must be a non-nil no-op: none of these messages declare
	// proto2 required fields, and without it google.golang.org/protobuf falls
	// back to a full protoreflect walk of the message tree after every
	// Marshal. That walk reaches embedded k8s.io/apimachinery types, which
	// carry no descriptors since k8s 0.36 and crash protoimpl's struct-tag
	// based (aberrant) reflection on their map fields.
	CheckInitialized: func(protoiface.CheckInitializedInput) (protoiface.CheckInitializedOutput, error) {
		return protoiface.CheckInitializedOutput{}, nil
	},
	Marshal: func(in protoiface.MarshalInput) (protoiface.MarshalOutput, error) {
		b, err := in.Message.(protoMessageView).shim.Marshal()
		if err != nil {
			return protoiface.MarshalOutput{}, err
		}
		return protoiface.MarshalOutput{Buf: append(in.Buf, b...)}, nil
	},
	Unmarshal: func(in protoiface.UnmarshalInput) (protoiface.UnmarshalOutput, error) {
		if err := in.Message.(protoMessageView).shim.Unmarshal(in.Buf); err != nil {
			return protoiface.UnmarshalOutput{}, err
		}
		return protoiface.UnmarshalOutput{}, nil
	},
	Size: func(in protoiface.SizeInput) protoiface.SizeOutput {
		return protoiface.SizeOutput{Size: in.Message.(protoMessageView).shim.Size()}
	},
}
`)

	for _, name := range names {
		shim := "protoShim" + name
		fmt.Fprintf(&b, `
// %[2]s is a method-less defined type sharing the memory layout of %[1]s so
// that protoadapt falls back to legacy (aberrant) wrapping instead of calling
// ProtoReflect recursively.
type %[2]s %[1]s

func (m *%[2]s) Reset()         { (*%[1]s)(m).Reset() }
func (m *%[2]s) String() string { return (*%[1]s)(m).String() }
func (*%[2]s) ProtoMessage()    {}
func (*%[2]s) Descriptor() ([]byte, []int) { return (*%[1]s)(nil).Descriptor() }
func (m *%[2]s) Marshal() ([]byte, error)  { return (*%[1]s)(m).Marshal() }
func (m *%[2]s) Unmarshal(b []byte) error  { return (*%[1]s)(m).Unmarshal(b) }
func (m *%[2]s) Size() int                 { return (*%[1]s)(m).Size() }

func (m *%[1]s) ProtoReflect() protoreflect.Message {
	s := (*%[2]s)(m)
	return protoMessageView{protoadapt.MessageV2Of(s).ProtoReflect(), s}
}
`, name, shim)
	}

	out := filepath.Join(filepath.Dir(os.Args[1]), "proto_reflect_compat.go")
	if err := os.WriteFile(out, []byte(b.String()), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "write %s: %v\n", out, err)
		os.Exit(1)
	}
	fmt.Printf("wrote %s (%d types)\n", out, len(names))
}
